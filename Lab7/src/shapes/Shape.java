package shapes;

/**
 * Мінімальний спільний контракт усіх фігур: у них є площа.
 * Це єдине, що справді спільне для Rectangle і Square, тому саме воно
 * є безпечною точкою підстановки (LSP).
 *
 * Контракт: area() > 0 завжди (інваріант гарантують Guard Clauses у конструкторах).
 */
public interface Shape {
    double area();
}
